'''
bool: allowed values: True, False
'''

a = True;
print(a) #To print the value of a
print(type(a)) #To print the type of a

x = 10;
y = 20;
z = x < y; #To check if x is less than y
print(z) #To print the value of z
print(type(z)) #To print the type of z

print(True + True);
print(True + False);
print(False + False);
print(False + True);
print(True * 1);
